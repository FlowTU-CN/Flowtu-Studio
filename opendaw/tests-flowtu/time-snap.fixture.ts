import assert from 'node:assert/strict'
Reflect.set(globalThis,'AudioWorkletNode',class {})
const {Snapping}=await import('../src/ui/timeline/Snapping')
const {getFrameRate}=await import('../src/flowtu/time-format')
const range={xToUnit:(x:number)=>x,unitsPerPixel:1} as never
const snapping=new Snapping(range)
const map={ppqnToSeconds:(p:number)=>p<=1920?p/1920:1+(p-1920)/960,secondsToPPQN:(s:number)=>s<=1?s*1920:1920+(s-1)*960}
const binding=snapping.registerTempoMap(map)
snapping.index=snapping.units.findIndex(unit=>unit.name==='10 ms')
assert.equal(snapping.round(1.003*1920),1930)
assert.equal(snapping.floor(1930),1930)
assert.equal(snapping.ceil(1930),1930)
assert.equal(snapping.next(1920),1930)
assert.equal(snapping.previous(1920),1901)
assert.equal(snapping.computeDelta(17,1958,17),1958-17)
snapping.index=snapping.units.findIndex(unit=>unit.name==='1 frame')
snapping.setFrameRate(getFrameRate('25'))
assert.equal(snapping.next(1920),1958)
assert.equal(snapping.previous(1920),1843)
snapping.setFrameRate(getFrameRate('29.97'))
assert.equal(snapping.round(map.secondsToPPQN(1.001)),1921)
assert.equal(snapping.next(1921),1953)
assert.equal(snapping.previous(1921),1858)
snapping.stepFiner();assert.equal(snapping.unit.name,'10 ms')
snapping.stepFiner();assert.equal(snapping.unit.name,'Off')
snapping.stepFiner();assert.equal(snapping.unit.name,'Off')
snapping.stepCoarser();assert.equal(snapping.unit.name,'10 ms')
snapping.stepCoarser();assert.equal(snapping.unit.name,'1 frame')
snapping.enabled=false
assert.equal(snapping.round(1921.3),1921)
assert.equal(snapping.next(1921),1922)
snapping.enabled=true
snapping.index=snapping.units.findIndex(unit=>unit.name==='1/4')
assert.equal(snapping.round(1000),960)
assert.equal(snapping.next(960),1920)
binding.terminate();snapping.terminate()
console.log('TIME_SNAP_OK')
