import assert from 'node:assert/strict'
Reflect.set(globalThis,'AudioWorkletNode',class {})
const {Option,Terminable,UUID}=await import('@opendaw/lib-std')
const {PPQN}=await import('@opendaw/lib-dsp')
const {ProjectSkeleton,InstrumentFactories,AudioRegionBoxAdapter,TrackBoxAdapter}=await import('@opendaw/studio-adapters')
const {AudioFileBox}=await import('@opendaw/studio-boxes')
const {Project,AudioContentFactory}=await import('@opendaw/studio-core')
const {editTrackAudioRange}=await import('../src/flowtu/range-edit')
const env={audioContext:{currentTime:0,sampleRate:48000,createGain:()=>({connect(){},disconnect(){},gain:{value:1}}),createStereoPanner:()=>({connect(){},disconnect(){},pan:{value:0}})},audioWorklets:undefined,sampleManager:{getOrCreate:(uuid:unknown)=>({get data(){return Option.None},get peaks(){return Option.None},get uuid(){return uuid},get state(){return {type:'idle'}},invalidate(){},subscribe:()=>Terminable.Empty}),record(){},invalidate(){},remove(){},register:()=>Terminable.Empty},soundfontManager:undefined,sampleService:undefined,soundfontService:undefined} as never
const project=Project.fromSkeleton(env,ProjectSkeleton.empty({createDefaultUser:true,createOutputMaximizer:false}))
const Q=PPQN.Quarter
const {track,a,b,file}=project.editing.modify(()=>{
 const {trackBox}=project.api.createInstrument(InstrumentFactories.Tape)
 const file=AudioFileBox.create(project.boxGraph,UUID.generate(),box=>{box.fileName.setValue('Range test');box.startInSeconds.setValue(0);box.endInSeconds.setValue(8)})
 const sample={name:'Audio',duration:4,bpm:0} as never
 const create=(position:number)=>project.boxAdapters.adapterFor(AudioContentFactory.createNotStretchedRegion({boxGraph:project.boxGraph,targetTrack:trackBox,audioFileBox:file,sample,position,waveformOffset:1}),AudioRegionBoxAdapter)
 return {track:project.boxAdapters.adapterFor(trackBox,TrackBoxAdapter),a:create(0),b:create(10*Q),file}
},true).unwrap()
const spans=()=>track.regions.collection.asArray().map(r=>[r.position/Q,r.complete/Q]).sort((a,b)=>a[0]-b[0])
assert.deepEqual(spans(),[[0,8],[10,18]])
const fragments=editTrackAudioRange(project,track,{start:2*Q,end:14*Q},'split')
assert.deepEqual(spans(),[[0,2],[2,8],[10,14],[14,18]])
assert.deepEqual(fragments.map(r=>[r.position/Q,r.complete/Q]),[[2,8],[10,14]])
assert.equal(fragments[0].loopOffset,2*Q)
assert.equal(fragments[1].loopOffset,0)
assert.equal(fragments[0].waveformOffset.getValue(),1)
assert.ok(fragments.every(r=>r.file.uuid.every((v,i)=>v===file.address.uuid[i])))
project.editing.undo()
assert.deepEqual(spans(),[[0,8],[10,18]])
assert.equal(a.loopOffset,0);assert.equal(b.loopOffset,0)
editTrackAudioRange(project,track,{start:2*Q,end:14*Q},'delete')
assert.deepEqual(spans(),[[0,2],[14,18]])
const tail=track.regions.collection.asArray().find(r=>r.position===14*Q) as InstanceType<typeof AudioRegionBoxAdapter>
assert.equal(tail.loopOffset,4*Q)
assert.equal(tail.waveformOffset.getValue(),1)
project.editing.undo()
assert.deepEqual(spans(),[[0,8],[10,18]])
assert.throws(()=>editTrackAudioRange(project,track,{start:8*Q,end:10*Q},'delete'))
assert.deepEqual(spans(),[[0,8],[10,18]])
// A Float32 duration of 1.1s reads slightly long. After splitting, the selected end must
// stay on the original edit tick, and selecting the next clip must not recut this one.
const {getTimelineSelection} = await import('../src/flowtu/timeline-selection')
const start = Math.round(project.tempoMap.secondsToPPQN(1.9)), end = Math.round(project.tempoMap.secondsToPPQN(3))
const [middle] = editTrackAudioRange(project,track,{start,end},'split')
assert.deepEqual(getTimelineSelection(project),{start,end})
assert.equal(project.regionSelection.selected()[0],middle)
const countAfterSplit = track.regions.collection.asArray().length
const next = editTrackAudioRange(project,track,{start:end,end:a.position+8*Q},'split')
assert.equal(next.length,1)
assert.equal(next[0].position,end)
assert.equal(track.regions.collection.asArray().length,countAfterSplit)
console.log('RANGE_GRAPH_OK: cross-clip split, gap preservation, source offsets, delete and one-step undo')

// Header groups follow visible ordering across different units. The keyboard delete acts on
// the group in one history step and leaves unselected tracks and their contents intact.
const {selectHeader,headerTargets,deleteHeaderSelection}=await import('../src/flowtu/track-selection')
const selectionProject=Project.fromSkeleton(env,ProjectSkeleton.empty({createDefaultUser:true,createOutputMaximizer:false}))
const lanes=selectionProject.editing.modify(()=>['A','B','C','D'].map(name=>{
    const {trackBox}=selectionProject.api.createInstrument(InstrumentFactories.Vaporisateur)
    selectionProject.api.createNoteRegion({trackBox,name,position:0,duration:Q})
    return selectionProject.boxAdapters.adapterFor(trackBox,TrackBoxAdapter)
}),true).unwrap()
const plain={shiftKey:false,ctrlKey:false,metaKey:false}
selectHeader(selectionProject,lanes[0],lanes,plain)
selectHeader(selectionProject,lanes[2],lanes,{...plain,shiftKey:true})
assert.deepEqual(headerTargets(selectionProject,lanes[2]),lanes.slice(0,3))
selectHeader(selectionProject,lanes[1],lanes,{...plain,ctrlKey:true})
assert.deepEqual(headerTargets(selectionProject,lanes[2]),[lanes[0],lanes[2]])
const {projectAssets}=await import('../src/flowtu/scoring-assets')
const originalMedia=()=>projectAssets(selectionProject).map(item=>[item.id,item.name]).sort()
const mediaBefore=originalMedia()
const channelIds=lanes.map(track=>track.audioUnit.address.uuid)
const channelsPresent=()=>channelIds.map(id=>selectionProject.boxGraph.findBox(id).nonEmpty())
deleteHeaderSelection(selectionProject,lanes[2])
const present=()=>lanes.map(t=>selectionProject.boxGraph.findBox(t.uuid).nonEmpty())
assert.deepEqual(present(),[false,true,false,true])
assert.deepEqual(channelsPresent(),[false,true,false,true])
assert.deepEqual(originalMedia(),mediaBefore)
assert.deepEqual(projectAssets(selectionProject).filter(item=>item.stored).map(item=>item.name).sort(),['A','C'])
selectionProject.editing.undo()
assert.deepEqual(present(),[true,true,true,true])

assert.deepEqual(channelsPresent(),[true,true,true,true])
assert.deepEqual(originalMedia(),mediaBefore)
assert.ok(projectAssets(selectionProject).every(item=>!item.stored))
selectionProject.editing.redo()
assert.deepEqual(channelsPresent(),[false,true,false,true])

// A volume lane and a content subtrack may each be deleted without removing their siblings.
const {AudioUnitBoxAdapter,TrackType,MetaData}=await import('@opendaw/studio-adapters')
const {overlapLaneOrigin}=await import('../src/flowtu/playback-lanes')
const {deleteTracksWithMedia}=await import('../src/flowtu/track-delete')
const laneProject=Project.fromSkeleton(env,ProjectSkeleton.empty({createDefaultUser:true,createOutputMaximizer:false}))
const current=(lane:{uuid:Uint8Array})=>laneProject.boxAdapters.adapterFor(laneProject.boxGraph.findBox(lane.uuid).unwrap(),TrackBoxAdapter)
const {owner,main,other,hidden,automation}=laneProject.editing.modify(()=>{
    const {trackBox,audioUnitBox}=laneProject.api.createInstrument(InstrumentFactories.Tape)
    const owner=laneProject.boxAdapters.adapterFor(audioUnitBox,AudioUnitBoxAdapter)
    const hidden=laneProject.api.createAudioTrack(audioUnitBox)
    MetaData.store(hidden,UUID.toString(trackBox.address.uuid),overlapLaneOrigin)
    const other=laneProject.api.createAudioTrack(audioUnitBox)
    const automation=owner.tracks.create(TrackType.Value,audioUnitBox.volume)
    return {owner,main:trackBox,hidden,other,automation}
},true).unwrap()
const exists=(box:{address:{uuid:Uint8Array}})=>laneProject.boxGraph.findBox(box.address.uuid).nonEmpty()
deleteTracksWithMedia(laneProject,[current({uuid:automation.address.uuid})])
assert.deepEqual([owner.box,main,hidden,other,automation].map(exists),[true,true,true,true,false])
laneProject.editing.undo()
deleteTracksWithMedia(laneProject,[current({uuid:main.address.uuid})])
assert.deepEqual([owner.box,main,hidden,other,automation].map(exists),[true,false,false,true,true])
deleteTracksWithMedia(laneProject,[current({uuid:other.address.uuid})])
assert.deepEqual([owner.box,main,hidden,other,automation].map(exists),[false,false,false,false,false])
laneProject.editing.undo()
assert.deepEqual([owner.box,main,hidden,other,automation].map(exists),[true,false,false,true,true])
