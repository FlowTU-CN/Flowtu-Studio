import assert from 'node:assert/strict'
Reflect.set(globalThis, 'AudioWorkletNode', class {})
const {UUID} = await import('@opendaw/lib-std')
const {ProjectSkeleton, InstrumentFactories, MetaData} = await import('@opendaw/studio-adapters')
const {Project} = await import('@opendaw/studio-core')
const {readFolders, folderOrigin, toggleFolder, memberSwitch, resetSwitches, folderTree, moveEntry} = await import('../src/flowtu/folder-tree')
const env = {audioContext: {currentTime: 0, sampleRate: 48000, createGain: () => ({connect(){},disconnect(){},gain:{value:1}}),createStereoPanner: () => ({connect(){},disconnect(){},pan:{value:0}})}} as never
const project = Project.fromSkeleton(env, ProjectSkeleton.empty({createDefaultUser:true,createOutputMaximizer:false}))
project.editing.modify(() => {for (let i=0; i<3; i++) {project.api.createInstrument(InstrumentFactories.Tape)}}, true)
const channels = project.rootBoxAdapter.audioUnits.adapters().filter(u => !u.isOutput)
const [a,b,c] = channels.map(u => UUID.toString(u.uuid))
const parent = crypto.randomUUID(), child = crypto.randomUUID()
const folder = (id:string, name:string, members:string[]) => ({id,name,members,collapsed:false,color:'#337799'})
// A v1 project has flat folders with arbitrary noncontiguous membership and no parent/order fields.
project.editing.modify(() => MetaData.store(project.rootBox, {folders:[folder(parent,'Band',[a]),folder(child,'Strings',[b])],colors:{}},folderOrigin),true)
const tree = () => folderTree(readFolders(project),[a,b,c])
assert.deepEqual(tree().children.get(''), [parent,child,c])
moveEntry(project,child,parent,'inside')
assert.deepEqual(tree().children.get(parent), [a,child])
moveEntry(project,parent,child,'inside')
assert.equal(tree().byId.get(child)?.parent,parent)
const mutes = () => channels.map(u => u.box.mute.getValue())
memberSwitch(project,channels[0],'mute').setValue(true)
toggleFolder(project,parent,'mute')
assert.deepEqual(mutes(), [true,true,false])
toggleFolder(project,child,'mute')
toggleFolder(project,parent,'mute')
assert.deepEqual(mutes(),[true,true,false])
memberSwitch(project,channels[1],'mute').setValue(false)
toggleFolder(project,child,'mute')
assert.deepEqual(mutes(),[true,false,false])
toggleFolder(project,parent,'solo')
assert.deepEqual(channels.map(u => u.box.solo.getValue()),[true,true,false])
moveEntry(project,b,c,'after')
assert.deepEqual(tree().children.get(''), [parent,c,b])
assert.equal(channels[1].box.solo.getValue(),false)
project.editing.undo()
assert.equal(tree().parents.get(b),child)
assert.equal(channels[1].box.solo.getValue(),true)
memberSwitch(project,channels[0],'solo').setValue(true)
const loaded=Project.load(env,project.toArrayBuffer() as ArrayBuffer)
toggleFolder(loaded,parent,'solo')
assert.deepEqual(loaded.rootBoxAdapter.audioUnits.adapters().filter(u=>!u.isOutput).map(u=>u.box.solo.getValue()),[true,false,false])
resetSwitches(project,'solo')
assert.deepEqual(channels.map(u=>u.box.solo.getValue()), [false,false,false])
assert.deepEqual(readFolders(project).held.solo,{})
// The tint belongs to the channel, so old and newly created MIDI regions resolve it through their current track.
const {setTrackColor, trackPalette, trackTint, contentHue} = await import('../src/flowtu/track-color')
const {Color} = await import('@opendaw/lib-std')
const {NoteRegionBoxAdapter} = await import('@opendaw/studio-adapters')
const {assignFolder} = await import('../src/flowtu/folder-tree')
const instrument = project.editing.modify(() => project.api.createInstrument(InstrumentFactories.Vaporisateur), true).unwrap()
const createPart = (position: number) => project.boxAdapters.adapterFor(project.editing.modify(() =>
    project.api.createNoteRegion({trackBox: instrument.trackBox, position, duration: 1920, name: 'Part'}), true).unwrap(), NoteRegionBoxAdapter)
const oldPart = createPart(0)
const owner = UUID.toString(oldPart.trackBoxAdapter.unwrap().audioUnit.address.uuid)
const originalHue = oldPart.hue
assert.equal(contentHue(oldPart), originalHue)
setTrackColor(project, owner, trackPalette.Violet)
const violet = Color.hexToHsl(trackPalette.Violet).h
assert.equal(contentHue(oldPart), violet)
project.editing.undo()
assert.equal(contentHue(oldPart), originalHue)
project.editing.redo()
const nextPart = createPart(1920)
assert.equal(contentHue(nextPart), violet)
const recalled = Project.load(env, project.toArrayBuffer() as ArrayBuffer)
const savedPart = recalled.boxAdapters.adapterFor(recalled.boxGraph.findBox(nextPart.uuid).unwrap() as typeof nextPart.box, NoteRegionBoxAdapter)
assert.equal(contentHue(savedPart), violet)
assert.equal(oldPart.hue, originalHue)
assignFolder(project, owner, child)
assert.equal(contentHue(oldPart), violet)
setTrackColor(project, owner)
assert.equal(contentHue(oldPart), Color.hexToHsl('#337799').h)
assignFolder(project, owner)
assert.equal(trackTint(oldPart.trackBoxAdapter.unwrap()), undefined)
assert.equal(contentHue(oldPart), originalHue)
console.log('FOLDERS_OK')
